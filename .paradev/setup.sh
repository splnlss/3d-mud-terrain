#!/usr/bin/env bash
# Runs once when Paradev creates a workspace. Safe to run again.
set -euo pipefail
. "$(dirname "$0")/lib.sh"
load_project_env
cd "$WORKSPACE_DIR"

log "workspace ${SUPERSET_WORKSPACE_NAME:-$(basename "$WORKSPACE_DIR")} at $WORKSPACE_DIR"

# 1. Toolchain
if { [ -f mise.toml ] || [ -f .mise.toml ] || [ -f .tool-versions ]; } && command -v mise >/dev/null 2>&1; then
  log "mise install"
  mise trust --quiet . >/dev/null 2>&1 || true
  mise install
fi

# 2. Dependencies
install_cmd="${INSTALL_CMD:-$(default_install_cmd)}"
if [ -n "$install_cmd" ]; then
  log "install: $install_cmd"
  sh -c "$install_cmd"
else
  log "install: nothing detected, skipping"
fi

# 3. Port block. Every name in PORT_NAMES gets base+i; PORT is the first.
base="$(allocate_port_block)"
compose_name="$(basename "$WORKSPACE_DIR" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9_-' '-' | sed 's/-*$//')"
{
  echo "# Generated by .paradev/setup.sh. Not committed."
  echo "PORT_BASE=$base"
  echo "PORT=$base"
  i=0
  for name in $PORT_NAMES; do
    echo "PORT_$(echo "$name" | tr 'a-z-' 'A-Z_')=$((base + i))"
    i=$((i + 1))
  done
  echo "COMPOSE_PROJECT_NAME=$compose_name"
} > "$WORKSPACE_ENV"

# Port labels for the Paradev ports panel, matching this workspace's numbers.
{
  echo '{ "ports": ['
  i=0
  for name in $PORT_NAMES; do
    [ "$i" -gt 0 ] && echo ','
    printf '  { "port": %d, "label": "%s" }' $((base + i)) "$name"
    i=$((i + 1))
  done
  echo; echo '] }'
} > "$PARADEV_DIR/ports.json"
log "ports: $(grep '^PORT_' "$WORKSPACE_ENV" | grep -v -E '^PORT_BASE=' | tr '\n' ' ')"

# 4. Doppler: secrets are injected at run time by with-secrets.sh, never written here.
if doppler_enabled; then
  if doppler_reachable; then
    log "doppler: $DOPPLER_PROJECT/$DOPPLER_CONFIG reachable"
  else
    warn "doppler: cannot read $DOPPLER_PROJECT/$DOPPLER_CONFIG (run 'doppler login'); the Run button will fail until then"
  fi
fi

# 5. Agent files are committed by new-project.sh, not fetched per workspace.
for p in .agents/skills .claude; do
  [ -e "$p" ] || warn "$p is missing on this branch; run new-project.sh from the kit and commit the result"
done

log "setup done"
